#!/usr/bin/env python3
"""Generates Sources/MimirCore/Generated/SharedPrompts.swift from shared/prompts.

shared/prompts is the source of truth for the prompts both the Mac app and
desktop/ (Rust) send to Claude. Run this after editing any file there; the
Swift test SharedPromptTests fails while the generated file is stale.
usage: python3 scripts/gen_shared_prompts.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PROMPTS = ROOT / "shared" / "prompts"
OUT = ROOT / "Sources" / "MimirCore" / "Generated" / "SharedPrompts.swift"

TEXTS = [
    ("cleanupLight", "cleanup-light.txt"),
    ("cleanupCleanDictation", "cleanup-clean-dictation.txt"),
    ("cleanupStructured", "cleanup-structured.txt"),
    ("cleanupPromptEngineer", "cleanup-prompt-engineer.txt"),
    ("cleanupVocabularySection", "cleanup-vocabulary-section.txt"),
    ("writingCheckSystem", "writing-check-system.txt"),
]


def literal(text: str) -> str:
    if '"""#' in text:
        raise SystemExit("prompt contains the raw-string delimiter")
    # Raw multiline literal at column 0: the content is exactly `text`.
    return '#"""\n' + text + '\n"""#'


def main() -> None:
    lines = [
        "// Generated by scripts/gen_shared_prompts.py from shared/prompts. Do not edit.",
        "// swiftlint:disable all",
        "",
        "enum SharedPrompts {",
    ]
    for name, filename in TEXTS:
        text = (PROMPTS / filename).read_text(encoding="utf-8")
        lines.append(f"    /// shared/prompts/{filename}")
        lines.append(f"    static let {name} = {literal(text)}")
        lines.append("")
    examples = json.loads((PROMPTS / "writing-check-examples.json").read_text(encoding="utf-8"))
    lines.append("    /// shared/prompts/writing-check-examples.json")
    lines.append("    static let writingCheckExamples: [(role: String, content: String)] = [")
    for item in examples:
        lines.append(f"        (role: {literal(item['role'])}, content: {literal(item['content'])}),")
    lines.append("    ]")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
